def lyrics_text(entry):
    v1, v2, c1, c2 = entry
    return f"[verse]\n{v1}\n{v2}\n[chorus]\n{c1}\n{c2}\n"


def plain_text(entry):
    return " ".join(entry)


def train_items(seeds_per_prompt=3):
    """54 lyric sets x 3 seeds = 162 clips; styles rotate so each lyric meets several styles."""
    items = []
    for i, entry in enumerate(TRAIN_LYRICS):
        for k in range(seeds_per_prompt):
            style = TRAIN_STYLES[(i * seeds_per_prompt + k) % len(TRAIN_STYLES)]
            items.append({"id": f"train-{i:03d}-{k}", "split": "train", "lyric_index": i,
                          "style": style, "lyrics": lyrics_text(entry), "reference": plain_text(entry),
                          "seed": 100_000 + i * 10 + k})
    return items


def eval_items():
    return [{"id": f"eval-{i:03d}", "split": "eval", "lyric_index": i,
             "style": EVAL_STYLES[i % len(EVAL_STYLES)], "lyrics": lyrics_text(e),
             "reference": plain_text(e), "seed": 900_000 + i}
            for i, e in enumerate(EVAL_LYRICS)]


